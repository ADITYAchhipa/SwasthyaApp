def run_translation_task(task):
    key, eng_val, lang = task
    val = get_translated_value(key, eng_val, lang)
    return key, lang, val

print(f"Starting concurrent translation of {len(tasks)} items...")
with concurrent.futures.ThreadPoolExecutor(max_workers=30) as executor:
    results = list(executor.map(run_translation_task, tasks))

for key, lang, val in results:
    translations_map[lang][key] = val

