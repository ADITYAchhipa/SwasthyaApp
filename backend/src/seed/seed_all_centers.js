async function seedAll() {
  console.log('🔄 Connecting to MongoDB...');
  await mongoose.connect(MONGO_URI);
  console.log('✅ Connected.');

  // Upsert Hospitals
  for (const h of hospitalsData) {
    await Hospital.findOneAndUpdate({ hospitalId: h.hospitalId }, h, { upsert: true, new: true });
    console.log(`🏥 Hospital upserted: ${h.name}`);
  }

  // Upsert PHCs
  for (const p of phcsData) {
    await Phc.findOneAndUpdate({ phcId: p.phcId }, p, { upsert: true, new: true });
    console.log(`🩺 PHC upserted: ${p.name}`);
  }

  // Upsert Blood Banks
  for (const b of bloodBanksData) {
    await BloodBank.findOneAndUpdate({ bloodBankId: b.bloodBankId }, b, { upsert: true, new: true });
    console.log(`🩸 Blood Bank upserted: ${b.name}`);
  }

  console.log('\n🎉 All Health Centers (Hospitals, PHCs, Blood Banks) seeded successfully!');
  await mongoose.disconnect();
  process.exit(0);
}

seedAll().catch(err => {
  console.error('❌ Seeding failed:', err);
  process.exit(1);
});
